-- =====================================================================
--  PixelForge - oefendatabase game-pc webshop (MySQL 8 / MariaDB)
--  Gemaakt voor SQL-oefeningen (MBO 4). Alle klantgegevens zijn verzonnen.
--
--  Tabellen (aantal rijen):
--    merken (22)  categorieen (11)  producten (70)
--    klanten (150)  bestellingen (420)  bestelregels (843)  reviews (172)
--
--  Relaties:
--    producten.merk_id       -> merken
--    producten.categorie_id  -> categorieen
--    bestellingen.klant_id   -> klanten
--    bestelregels            -> bestellingen + producten  (koppeltabel)
--    reviews                 -> producten + klanten
-- =====================================================================

DROP DATABASE IF EXISTS `oefen-database`;
CREATE DATABASE `oefen-database` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `oefen-database`;

CREATE TABLE merken (
  merk_id      INT AUTO_INCREMENT PRIMARY KEY,
  naam         VARCHAR(50)  NOT NULL UNIQUE,
  land         VARCHAR(50)  NOT NULL,
  opgericht    SMALLINT
) ENGINE=InnoDB;

CREATE TABLE categorieen (
  categorie_id INT AUTO_INCREMENT PRIMARY KEY,
  naam         VARCHAR(50)  NOT NULL UNIQUE,
  omschrijving VARCHAR(255)
) ENGINE=InnoDB;

CREATE TABLE producten (
  product_id        INT AUTO_INCREMENT PRIMARY KEY,
  naam              VARCHAR(100) NOT NULL,
  merk_id           INT          NOT NULL,
  categorie_id      INT          NOT NULL,
  prijs             DECIMAL(8,2) NOT NULL,
  voorraad          INT          NOT NULL DEFAULT 0,
  garantie_maanden  INT          NOT NULL,
  toegevoegd_op     DATE         NOT NULL,
  FOREIGN KEY (merk_id)      REFERENCES merken(merk_id),
  FOREIGN KEY (categorie_id) REFERENCES categorieen(categorie_id)
) ENGINE=InnoDB;

CREATE TABLE klanten (
  klant_id         INT AUTO_INCREMENT PRIMARY KEY,
  voornaam         VARCHAR(50)  NOT NULL,
  tussenvoegsel    VARCHAR(15),
  achternaam       VARCHAR(50)  NOT NULL,
  email            VARCHAR(100) NOT NULL UNIQUE,
  telefoon         VARCHAR(15),
  woonplaats       VARCHAR(50),
  postcode         VARCHAR(7),
  geboortedatum    DATE,
  geregistreerd_op DATE         NOT NULL,
  nieuwsbrief      TINYINT(1)   NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE bestellingen (
  bestelling_id  INT AUTO_INCREMENT PRIMARY KEY,
  klant_id       INT      NOT NULL,
  besteld_op     DATETIME NOT NULL,
  status         ENUM('betaald','verzonden','geleverd','geannuleerd','retour') NOT NULL,
  verzendmethode ENUM('PostNL','DHL','Afhalen') NOT NULL,
  kortingscode   VARCHAR(20),
  FOREIGN KEY (klant_id) REFERENCES klanten(klant_id)
) ENGINE=InnoDB;

CREATE TABLE bestelregels (
  bestelling_id INT          NOT NULL,
  product_id    INT          NOT NULL,
  aantal        INT          NOT NULL,
  stukprijs     DECIMAL(8,2) NOT NULL,
  PRIMARY KEY (bestelling_id, product_id),
  FOREIGN KEY (bestelling_id) REFERENCES bestellingen(bestelling_id),
  FOREIGN KEY (product_id)    REFERENCES producten(product_id)
) ENGINE=InnoDB;

CREATE TABLE reviews (
  review_id   INT AUTO_INCREMENT PRIMARY KEY,
  product_id  INT     NOT NULL,
  klant_id    INT     NOT NULL,
  sterren     TINYINT NOT NULL CHECK (sterren BETWEEN 1 AND 5),
  tekst       VARCHAR(255),
  geplaatst_op DATE   NOT NULL,
  FOREIGN KEY (product_id) REFERENCES producten(product_id),
  FOREIGN KEY (klant_id)   REFERENCES klanten(klant_id)
) ENGINE=InnoDB;

